#!/usr/bin/env python3
"""Build and copy only public website files into dist/."""
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'dist'
MARKER = OUTPUT / '.portfolio-build'


def main():
    subprocess.run([sys.executable, str(ROOT/'scripts/build.py')], check=True)
    subprocess.run([sys.executable, str(ROOT/'scripts/check.py')], check=True)
    # Refuse to overwrite a directory not created by this packager.
    if OUTPUT.exists():
        if not MARKER.is_file():
            raise SystemExit('dist/ exists without a portfolio build marker; choose a clean output directory.')
        shutil.rmtree(OUTPUT)
    OUTPUT.mkdir()
    MARKER.write_text('Generated by scripts/package.py\n')
    for name in ('index.html', '404.html', 'styles.css', 'app.js', '_headers', '_redirects'):
        shutil.copy2(ROOT/name, OUTPUT/name)
    for name in ('work', 'about', 'contact', 'assets'):
        shutil.copytree(ROOT/name, OUTPUT/name)
    size = sum(p.stat().st_size for p in OUTPUT.rglob('*') if p.is_file())
    print(f'Packaged public website: {OUTPUT} ({size / 1_000_000:.2f} MB).')


if __name__ == '__main__':
    main()
